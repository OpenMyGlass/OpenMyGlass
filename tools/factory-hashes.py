#!/usr/bin/env python3
"""Lists SHA-256 hashes of the binaries in the XE24 factory image (facts only, no content).

Usage: factory-hashes.py <factory-dir> > tools/factory-blobs.sha256

<factory-dir> holds the unpacked factory image: system.raw (ext4), ramdisk/ (unpacked) and the
*.img files. Every .apk, .odex, .jar and .so file in the system partition and the ramdisk is
hashed, plus the partition images themselves. Files are streamed with debugfs, nothing is written
to disk. tools/check-clean-room.sh fails if a tracked file has one of these hashes.
"""
import hashlib
import os
import shutil
import subprocess
import sys

EXTS = (".apk", ".odex", ".jar", ".so")
IMAGES = ("glass_1-img-5585826.zip", "boot.img", "recovery.img", "system.img", "system.raw")


def debugfs_bin():
    for c in (shutil.which("debugfs"), "/opt/homebrew/opt/e2fsprogs/sbin/debugfs", "/usr/local/opt/e2fsprogs/sbin/debugfs", "/sbin/debugfs"):
        if c and os.access(c, os.X_OK):
            return c
    sys.exit("debugfs not found (install e2fsprogs)")


def debugfs(dbg, image, cmd):
    r = subprocess.run([dbg, "-R", cmd, image], capture_output=True, check=True)
    # debugfs exits 0 on most errors: treat any message other than its version banner as one
    err = [l for l in r.stderr.decode("utf-8", "replace").splitlines() if l.strip() and not l.startswith("debugfs ")]
    if err:
        sys.exit(f"debugfs {cmd!r}: {err[0]}")
    return r.stdout


def walk(dbg, image, path):
    for line in debugfs(dbg, image, f'ls -p "{path}"').decode("utf-8", "replace").splitlines():
        parts = line.split("/")
        if len(parts) < 7:
            continue
        mode, name = parts[2], parts[5]
        if name in (".", ".."):
            continue
        full = f"{path.rstrip('/')}/{name}"
        if mode.startswith("04"):
            yield from walk(dbg, image, full)
        elif mode.startswith("10"):
            yield full


def sha256_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    root = sys.argv[1]
    rows = []
    for name in IMAGES:
        p = os.path.join(root, name)
        if os.path.isfile(p):
            rows.append((sha256_file(p), name))
    system = os.path.join(root, "system.raw")
    if os.path.isfile(system):
        dbg = debugfs_bin()
        for f in walk(dbg, system, "/"):
            if f.lower().endswith(EXTS):
                data = debugfs(dbg, system, f'cat "{f}"')
                if not data:
                    sys.exit(f"empty read from {f}: refusing to list the hash of empty input")
                rows.append((hashlib.sha256(data).hexdigest(), "system" + f))
    ramdisk = os.path.join(root, "ramdisk")
    for d, _, files in os.walk(ramdisk):
        for n in files:
            p = os.path.join(d, n)
            if n.lower().endswith(EXTS) and os.path.isfile(p) and not os.path.islink(p):
                rows.append((sha256_file(p), "ramdisk/" + os.path.relpath(p, ramdisk)))
    print("# SHA-256 of binaries in the Glass XE24 factory image glass_1-img-5585826 (generated by tools/factory-hashes.py)")
    for h, n in sorted(rows, key=lambda r: r[1]):
        print(f"{h}  {n}")


if __name__ == "__main__":
    main()
